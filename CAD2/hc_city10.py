def scatter(x, y, labels, **kw):
    
    plt.figure(figsize=(6, 4))
    plt.yticks(size=12)
    plt.xticks(size=12)
    plt.scatter(x, y)
    for xx, yy, label in zip(x, y, labels):
        plt.text(xx, yy, '%s.' % label, 
                 ha='center', va='bottom', **kw)
plt.show()


# 画图，x,y，标签
#你的代码
x=new_model_data["Gross"]
